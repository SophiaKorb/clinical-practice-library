'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const js=fs.readFileSync(path.join(root,'resources/clinical-finder.js'),'utf8');
const css=fs.readFileSync(path.join(root,'resources/clinical-finder.css'),'utf8');
const raw=fs.readFileSync(path.join(root,'resources/clinical-finder-data.js'),'utf8');
const data=JSON.parse(raw.replace(/^globalThis\.CPLFinderData\s*=\s*/,'').replace(/;\s*$/,''));
assert(js.includes("card.appendChild(heading);"),'Result card should contain heading only (plus optional direct-use badge)');
assert(!js.includes("meta.textContent=r.format"),'No meaningless file format and Current Colorful status on results');
assert(!js.includes("const recommended=related(r,data.resources)"),'Related-resource accordion must not appear on every search result');
assert(!js.includes("tag.textContent=t"),'Internal diagnosis/function/audience tags must not be displayed as chips');
assert(!js.includes("Discovery tags are not clinical approval."),'Do not repeat site guidance on every result count');
assert(js.includes("const found=search(data.resources,state).filter(r=>matchesAge(r,state.age))"),'Search and age filtering must remain');
assert(js.includes("heading.appendChild(badge)"),'Approved directly-facing age badges must survive');
assert(css.includes('.finder-card h3 a:hover'),'Simplified result affordance styled');
assert(data.resources.length>=529,'Existing indexed resources must not disappear');
console.log('PASS finder result simplification; search and age markers preserved, '+data.resources.length+' indexed resource entries retained.');
