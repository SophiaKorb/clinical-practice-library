'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=x=>fs.readFileSync(path.join(root,x),'utf8');
const d=JSON.parse(read('resources/clinical-finder-data.js').replace(/^globalThis\.CPLFinderData\s*=\s*/,'').replace(/;\s*$/,''));
const finder=require('../resources/clinical-finder.js');
const base='/resources/community/expanded-external-resources.html#';
const rows=d.resources.filter(x=>x.url.startsWith(base));
const byTitle=t=>{const v=rows.filter(x=>x.title===t);assert.equal(v.length,1,'Expected exactly one '+t);return v[0];};
const byId=id=>{const r=rows.find(x=>x.url===base+id);assert(r,'Missing source '+id);return r;};
assert.equal(d.resources.length,609,'Production catalog count preserved');
assert.equal(rows.length,77,'Audit must not add/remove publisher entries');
assert.equal(new Set(d.resources.map(x=>x.url)).size,609,'No duplicate CPL URLs');
assert.equal(new Set(rows.map(x=>x.externalUrl)).size,77,'No duplicate external provider URLs');
const html=read('resources/community/expanded-external-resources.html');
for(const r of rows){
 const id=r.url.slice(base.length),cardStart='<article class="card" id="'+id+'"><h3>';
 assert(html.includes(cardStart),'Missing listing '+id);
 assert(html.includes('href="'+r.externalUrl.replace(/&/g,'&amp;')+'"'),'Directory URL does not match source '+id);
 assert(html.includes(r.title.replace(/&/g,'&amp;')),'Directory title does not match indexed title '+id);
 assert.equal(r.sourceAuditDate,'2026-11-16','Record missing review date '+id);
 for(const[k,values]of Object.entries(r.tags))for(const val of values)assert(d.facets[k]?.includes(val),'Invalid '+k+':'+val+' in '+id);
}
const young=byTitle('Tweens, teens and young adults');
assert.equal(young.minimumAge,undefined,'Source includes tweens about ages 9–12: do not assert min age 13');
assert(finder.matchesAge(young,'children')&&finder.matchesAge(young,'teens')&&finder.matchesAge(young,'adults'),'All intended tween/teen/young adult audiences must find this hub');
const recovery=byId('ext-05-04');
assert.deepEqual(recovery.tags.stage,['Adult']);
assert.equal(recovery.minimumAge,undefined);assert.equal(recovery.maximumAge,undefined);
assert(recovery.ageScopeBasis.includes('18–25'),'SAMHSA priority audience must remain documented without an artificial service age gate');
assert(!finder.matchesAge(recovery,'children')&&!finder.matchesAge(recovery,'teens')&&finder.matchesAge(recovery,'adults'),'RecoverMe adult campaign age filter');
const elder=byId('ext-04-04');
assert.deepEqual(elder.tags.stage,['Adult']);
assert(!finder.matchesAge(elder,'children')&&finder.matchesAge(elder,'adults'),'Eldercare no pediatric matches');
assert(!elder.tags.role.includes('School team'),'Eldercare should not surface under school-team filter');
const cdc=byTitle('CDC ADHD education resources');
assert.equal(cdc.externalUrl,'https://www.cdc.gov/adhd/php/communication-resources/index.html');
assert(!html.includes('href="https://www.cdc.gov/adhd/communication-resources/index.html"'),'Old unreadable link must not remain');
const va=byTitle('VA AboutFace — PTSD tools for professionals');
assert(va.tags.role.includes('Clinician')&&!va.tags.role.includes('Client / caregiver'),'Clinical professional materials properly marked');
const acl=byTitle('ACL National Resource Centers — professional and agency guidance');
assert(!acl.tags.role.includes('Client / caregiver'),'Institutional ACL centers must not be presented as a client intake');
const hsrc=byTitle('Housing and Services Resource Center — partner guidance');
assert(!hsrc.tags.role.includes('Client / caregiver'),'Housing technical-assistance hub not consumer direct intake');
const arizona=byTitle('AHCCCS Arizona 988 implementation — agency information');
assert(!arizona.tags.role.includes('Client / caregiver'),'988 grant detail should not substitute for Arizona crisis intake');
const yv=byTitle('Youth Voice, Youth Choice — resource library (project concluded)');
assert(/conclu/i.test(yv.programStatus)&&yv.externalUrl==='https://youth-voice.org/','Project status should reflect publisher farewell');
const parent=byId('ext-06-04');
assert(parent.tags.stage.includes('Early childhood'),'IDEA centers include birth to age 26');
for(const name of ['Child depression and mood','Learning disorders','Screen time and technology','Behavior problems','Autism in childhood','Anxiety in children','ADHD and attention','Developmental milestones guide','Managing child behavior problems guide','Parent guide to autism','Selective mutism guide'])assert(byTitle(name).tags.stage.includes('Early childhood'),'Missing evidenced preschool resource '+name);
assert(read('index.html').includes('<details class="cpl-disclosure"><summary>Independence &amp; disclaimer</summary>'),'Preserve homepage original disclosure');
const ledger=read('docs/qa/2026-11-16-cpl-77-link-primary-source-audit.md');
assert((ledger.match(/^\| \d{2} \|/gm)||[]).length===77,'Audited ledger must contain exactly 77 entries');
console.log('PASS 77 original provider sources, 609 indexed entries, corrected CDC route, tween/young adult/elders, professional roles, and 77-item evidence ledger');
